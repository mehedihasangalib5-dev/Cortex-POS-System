    function getLang() {
        return localStorage.getItem('lang') || 'en';
    }

    function applyTranslations(lang) {
        const dict = translations[lang] || translations.en;

        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            const key = el.getAttribute('data-i18n');
            if (dict[key] !== undefined) {
                el.textContent = dict[key];
            }
        });

        document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
            const key = el.getAttribute('data-i18n-html');
            if (dict[key] !== undefined) {
                el.innerHTML = dict[key];
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            const key = el.getAttribute('data-i18n-placeholder');
            if (dict[key] !== undefined) {
                el.setAttribute('placeholder', dict[key]);
            }
        });

        document.documentElement.setAttribute('lang', lang === 'bn' ? 'bn' : 'en');

        document.querySelectorAll('[data-lang-toggle]').forEach(function (btn) {
            btn.querySelectorAll('[data-lang-option]').forEach(function (opt) {
                const isActive = opt.getAttribute('data-lang-option') === lang;
                opt.classList.toggle('lang-active', isActive);
            });
        });
    }

    function setLang(lang) {
        localStorage.setItem('lang', lang);
        applyTranslations(lang);
    }

    window.setLang = setLang;
    window.getLang = getLang;
    window.i18nText = function (key) {
        const dict = translations[getLang()] || translations.en;
        return dict[key] !== undefined ? dict[key] : key;
    };

    document.addEventListener('DOMContentLoaded', function () {
        applyTranslations(getLang());

        document.querySelectorAll('[data-lang-toggle]').forEach(function (btn) {
            btn.querySelectorAll('[data-lang-option]').forEach(function (opt) {
                opt.addEventListener('click', function () {
                    setLang(opt.getAttribute('data-lang-option'));
                });
            });
        });
    });
